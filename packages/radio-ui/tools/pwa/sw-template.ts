// Service worker generator (no dependencies). Vietnamese: sinh sw.js lúc build, precache toàn bộ app shell để chạy offline.
// Cache-first for same-origin GETs; navigations fall back to the cached index.html; a new worker waits until every tab is
// closed (no skipWaiting), so a running game is never swapped under the player.

const FNV_OFFSET = 0x811c9dc5;

/** 32-bit FNV-1a over a string: stable cache version derived from the precache list and the HTML shell. */
export function cacheVersion(material: string): string {
  let h = FNV_OFFSET;
  for (let i = 0; i < material.length; i++) { h ^= material.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, "0");
}

/** Files that must never be precached: source maps and the worker itself. */
export function precacheFiles(files: readonly string[]): string[] {
  return [...new Set(files)]
    .filter((f) => !f.endsWith(".map") && f !== "sw.js")
    .sort();
}

export function buildServiceWorker(files: readonly string[], htmlSource: string): string {
  const list = precacheFiles(files).map((f) => `./${f}`);
  const version = cacheVersion(`${list.join("\n")}\n${htmlSource}`);
  return `// Generated by tools/pwa/sw-template.ts at build time. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "uboat-radio-" + VERSION;
const PRECACHE = ${JSON.stringify(["./", ...list], null, 2)};
// Module scripts and fonts are CORS requests; servers often answer with "Vary: Origin", which would make the stored copy
// (fetched without an Origin header) miss. The files are immutable per build, so Vary is ignored.
const MATCH = { ignoreVary: true };

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("uboat-radio-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  if (new URL(req.url).origin !== self.location.origin) return; // never touch cross-origin traffic
  if (req.mode === "navigate") {
    event.respondWith(caches.match("./index.html", MATCH).then((hit) => hit || fetch(req)));
    return;
  }
  event.respondWith(caches.match(req, MATCH).then((hit) => hit || fetch(req)));
});
`;
}
