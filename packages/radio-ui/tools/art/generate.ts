// Usage (from packages/radio-ui):  node tools/art/generate.ts
// Writes assets/sprites/*.png and assets/manifest.json. Deterministic: same source => same pixels (pixelSha256 is stable across Node versions).
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { encodePng } from "./pix.ts";
import { iconSprites } from "./icons.ts";
import { buildSprites } from "./sprites.ts";

const sha = (b: Uint8Array): string => createHash("sha256").update(b).digest("hex");

export interface ManifestEntry {
  id: string; path: string; width: number; height: number;
  frames: { w: number; h: number; count: number } | null;
  origin: string; license: string; status: "TEMPORARY"; note: string; sha256: string; pixelSha256: string;
}

export function buildManifest(): { entries: ManifestEntry[]; files: Map<string, Uint8Array> } {
  const entries: ManifestEntry[] = [];
  const files = new Map<string, Uint8Array>();
  const all = [...buildSprites().map((s) => ({ s, path: `sprites/${s.id}.png` })), ...iconSprites().map((i) => ({ s: i.sprite, path: i.path }))];
  for (const { s, path } of all) {
    const png = encodePng(s.img);
    files.set(path, png);
    entries.push({
      id: s.id, path, width: s.img.w, height: s.img.h, frames: s.frames ?? null,
      origin: "generated by packages/radio-ui/tools/art/generate.ts (original placeholder art by the assistant)",
      license: "project license (original work, no third-party pixels)", status: "TEMPORARY", note: s.note,
      sha256: sha(png), pixelSha256: sha(s.img.pixelBytes()),
    });
  }
  return { entries, files };
}

export const FONTS = [
  { id: "silkscreen-latin-400", path: "fonts/silkscreen-latin-400-normal.woff2", license: "OFL-1.1", licenseFile: "fonts/LICENSE-OFL-Silkscreen.txt", origin: "@fontsource/silkscreen@5.3.0 (npm tarball, not a dependency)", sha256: "e6c72ea4702249202bcdd79d3343057e4e25ef1f04e3fcffd8602ab53b40b4cc" },
  { id: "vt323-latin-400", path: "fonts/vt323-latin-400-normal.woff2", license: "OFL-1.1", licenseFile: "fonts/LICENSE-OFL-VT323.txt", origin: "@fontsource/vt323@5.3.0 (npm tarball, not a dependency)", sha256: "8ddbebcc1048154132e1d78eb9b1f7850bca1b7d857035ccf1cb4318ebc615b6" },
] as const;

// Run as a script only when invoked directly (not when imported by tests).
const entryUrl = (globalThis as { process?: { argv?: string[] } }).process?.argv?.[1] ?? "";
if (entryUrl.endsWith("generate.ts")) {
  const { entries, files } = buildManifest();
  mkdirSync("assets/sprites", { recursive: true });
  mkdirSync("public/icons", { recursive: true });
  for (const [p, b] of files) writeFileSync(`assets/${p}`, b);
  writeFileSync("assets/manifest.json", `${JSON.stringify({ schema: 1, scene: { width: 640, height: 360 }, sprites: entries, fonts: FONTS }, null, 2)}\n`);
  console.log(`wrote ${entries.length} sprites`);
}
